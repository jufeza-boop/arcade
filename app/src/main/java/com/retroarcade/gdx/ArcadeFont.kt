        ':' to intArrayOf(0x00, 0x06, 0x06, 0x00, 0x06, 0x06, 0x00),
        '.' to intArrayOf(0x00, 0x00, 0x00, 0x00, 0x00, 0x06, 0x06),
        ',' to intArrayOf(0x00, 0x00, 0x00, 0x00, 0x06, 0x06, 0x04),
        '!' to intArrayOf(0x04, 0x04, 0x04, 0x04, 0x04, 0x00, 0x04),
        '?' to intArrayOf(0x0E, 0x11, 0x01, 0x06, 0x04, 0x00, 0x04),
        '<' to intArrayOf(0x02, 0x04, 0x08, 0x10, 0x08, 0x04, 0x02),
        '>' to intArrayOf(0x08, 0x04, 0x02, 0x01, 0x02, 0x04, 0x08),
        '/' to intArrayOf(0x01, 0x02, 0x02, 0x04, 0x08, 0x08, 0x10),
        '#' to intArrayOf(0x0A, 0x0A, 0x1F, 0x0A, 0x1F, 0x0A, 0x0A),
        '*' to intArrayOf(0x00, 0x15, 0x0E, 0x1F, 0x0E, 0x15, 0x00),
        '[' to intArrayOf(0x0E, 0x08, 0x08, 0x08, 0x08, 0x08, 0x0E),
        ']' to intArrayOf(0x0E, 0x02, 0x02, 0x02, 0x02, 0x02, 0x0E),
        '(' to intArrayOf(0x04, 0x08, 0x08, 0x08, 0x08, 0x08, 0x04),
        ')' to intArrayOf(0x04, 0x02, 0x02, 0x02, 0x02, 0x02, 0x04),
        '+' to intArrayOf(0x00, 0x04, 0x04, 0x1F, 0x04, 0x04, 0x00),
        '|' to intArrayOf(0x04, 0x04, 0x04, 0x04, 0x04, 0x04, 0x04)
    )

    private fun sanitizeChar(c: Char): Char = when (c) {
        'Á', 'À', 'Â', 'Ä' -> 'A'
        'É', 'È', 'Ê', 'Ë' -> 'E'
        'Í', 'Ì', 'Î', 'Ï' -> 'I'
        'Ó', 'Ò', 'Ô', 'Ö' -> 'O'
        'Ú', 'Ù', 'Û', 'Ü' -> 'U'
        'Ñ' -> 'N'
        else -> c
    }

    fun getTextWidth(text: String, pixelSize: Float, spacing: Float = pixelSize): Float {
        if (text.isEmpty()) return 0f
        val charWidth = CHAR_WIDTH_BITS * pixelSize
        return text.length * charWidth + (text.length - 1) * spacing
    }

    fun getTextHeight(pixelSize: Float): Float {
        return CHAR_HEIGHT_BITS * pixelSize
    }

    fun drawText(
        renderer: ShapeRenderer,
        text: String,
        startX: Float,
        startY: Float,
        pixelSize: Float = 3f,
        color: Color = Color.WHITE,
        spacing: Float = pixelSize
    ) {
        val upperText = text.uppercase()
        var curX = startX
        renderer.color = color

        for (rawCh in upperText) {
            val ch = sanitizeChar(rawCh)
            val glyph = GLYPHS[ch] ?: GLYPHS['?'] ?: intArrayOf(0, 0, 0, 0, 0, 0, 0)
            for (row in 0 until CHAR_HEIGHT_BITS) {
                val rowBits = glyph[row]
                val y = startY + (CHAR_HEIGHT_BITS - 1 - row) * pixelSize

                for (col in 0 until CHAR_WIDTH_BITS) {
                    val bit = (rowBits shr (CHAR_WIDTH_BITS - 1 - col)) and 1
                    if (bit == 1) {
                        val x = curX + col * pixelSize
                        renderer.rect(x, y, pixelSize, pixelSize)
                    }
                }
            }
            curX += CHAR_WIDTH_BITS * pixelSize + spacing
        }
    }

    fun drawCenteredText(
        renderer: ShapeRenderer,
        text: String,
        centerX: Float,
        centerY: Float,
        pixelSize: Float = 3f,
        color: Color = Color.WHITE,
        spacing: Float = pixelSize
    ) {
        val totalWidth = getTextWidth(text, pixelSize, spacing)
        val totalHeight = getTextHeight(pixelSize)
        val startX = centerX - totalWidth / 2f
        val startY = centerY - totalHeight / 2f
        drawText(renderer, text, startX, startY, pixelSize, color, spacing)
    }
}
