package com.retroarcade.gdx

import com.badlogic.gdx.graphics.Color
import com.badlogic.gdx.graphics.glutils.ShapeRenderer

/**
 * Renderizador tipográfico arcade procedural 100% vectorial (matriz 5x7).
 * Dibuja exclusivamente con ShapeRenderer.ShapeType.Filled.
 * Cero dependencias de archivos, fuentes o assets externos.
 */
object ArcadeFont {

    const val CHAR_WIDTH_BITS = 5
    const val CHAR_HEIGHT_BITS = 7

